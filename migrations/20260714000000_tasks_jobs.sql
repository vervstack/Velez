CREATE TYPE velez.task_status AS ENUM (
    'PENDING',
    'RUNNING',
    'DONE',
    'FAILED'
    );

CREATE TABLE IF NOT EXISTS velez.tasks
(
    id         INT8 GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    entity_id  TEXT             NOT NULL,
    action     TEXT             NOT NULL,
    status     velez.task_status NOT NULL DEFAULT 'PENDING',
    context    JSON,
    error      TEXT,
    claimed_at TIMESTAMPTZ,
    claimed_by TEXT,
    created_at TIMESTAMPTZ      NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ      NOT NULL DEFAULT now(),
    UNIQUE (entity_id, action)
);

CREATE TYPE velez.job_status AS ENUM (
    'RUNNING',
    'DONE',
    'FAILED'
    );

CREATE TABLE IF NOT EXISTS velez.jobs
(
    id         INT8 GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    task_id    INT8            NOT NULL REFERENCES velez.tasks (id),
    job_name   TEXT            NOT NULL,
    status     velez.job_status NOT NULL,
    error      TEXT,
    created_at TIMESTAMPTZ     NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ     NOT NULL DEFAULT now(),
    UNIQUE (task_id, job_name)
);

