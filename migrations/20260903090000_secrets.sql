(
    id         INT8 GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    scope      TEXT        NOT NULL,
    owner      TEXT        NOT NULL,
    key        TEXT        NOT NULL,
    value      TEXT        NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    UNIQUE (scope, owner, key)
);

