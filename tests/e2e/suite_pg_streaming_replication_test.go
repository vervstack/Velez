const (
	pgStreamingTimeout = 60 * time.Second
	pgStreamingPoll    = 2 * time.Second

	pgStreamingFixture = `
CREATE TYPE workbench_status AS ENUM ('created', 'running', 'stopped', 'removed');

CREATE TABLE users (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    name TEXT NOT NULL
);

CREATE TABLE subscriptions (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    user_id UUID NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    active BOOLEAN NOT NULL DEFAULT FALSE,
    UNIQUE(user_id)
);

CREATE TABLE workbenches (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    user_id UUID NOT NULL REFERENCES users(id),
    status workbench_status NOT NULL DEFAULT 'created'
);

INSERT INTO users (name) VALUES ('Ada'), ('Grace');
INSERT INTO subscriptions (user_id, active) SELECT id, name = 'Ada' FROM users;
INSERT INTO workbenches (user_id, status)
    SELECT id, 'running'::workbench_status FROM users WHERE name = 'Ada';
INSERT INTO workbenches (user_id)
    SELECT id FROM users WHERE name = 'Grace';

CREATE TABLE replicated_rows (id serial PRIMARY KEY, value text NOT NULL);
INSERT INTO replicated_rows (value) VALUES ('first'), ('second'), ('third');
CREATE ROLE fixture_writer LOGIN PASSWORD 'fixture_pw';
GRANT SELECT, INSERT ON TABLE replicated_rows TO fixture_writer;
GRANT USAGE, SELECT ON SEQUENCE replicated_rows_id_seq TO fixture_writer;
`

	// nextval can pre-log future values in WAL. setval records the exact
	// value generated by the insert so the standby can assert last_value.
	pgStreamingInsert = `
WITH inserted AS (
    INSERT INTO replicated_rows (value) VALUES ('fourth') RETURNING id
)
SELECT setval('replicated_rows_id_seq', id) FROM inserted;
`
)

type PgStreamingReplicationSuite struct {
	suite.Suite

	plane Plane
}

func (s *PgStreamingReplicationSuite) Test_StreamsPhysicalReplica() {
	t := s.T()
	t.Parallel()

	env := s.plane.NewEnvironment(t)
	suffix := "-" + string(s.plane.Mode)
	source := createPgWithCleanup(t, env, "e2e-stream-src"+suffix)

	runReplicationSql(t, env, source, pgStreamingFixture)
	enablePgStreaming(t, env, source.GetName())

	target := createPgWithCleanup(t, env, "e2e-stream-dst"+suffix)

	setupPgStreaming(t, env, source.GetName(), target.GetName())
	requirePgStreamingStatus(t, env, source.GetName(), target.GetName())

	creds := getPgCredentials(t, env, target.GetName())
	require.Equal(t, source.GetUsername(), creds.GetUsername())
	require.Equal(t, source.GetDbName(), creds.GetDbName())

	db := openPostgresViaDind(t, creds.GetDsn(), env.DindDialContext)

	requirePgStreamingFixture(t, db)
	runReplicationSql(t, env, source, pgStreamingInsert)
	requirePgStreamingInsert(t, db)

	dropPgAndAwait(t, env, target.GetName())
	dropPgAndAwait(t, env, source.GetName())
}

