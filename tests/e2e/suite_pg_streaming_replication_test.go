func requirePgStreamingStatus(t *testing.T, env *TestEnvironment, source, target string) {
	t.Helper()

	ctx, cancel := context.WithTimeout(t.Context(), pgStreamingTimeout)
	defer cancel()

	sourceReq := &velez_api.GetPgReplicationStatus_Request{Instance: source}

	require.EventuallyWithT(t, func(c *assert.CollectT) {
		status, err := env.PgaasClient().GetPgReplicationStatus(ctx, sourceReq)
		if !assert.NoError(c, err) || !assert.Len(c, status.GetReplicas(), 1) {
			return
		}

		replica := status.GetReplicas()[0]
		assert.Equal(c, target, replica.GetApplicationName())
		assert.Equal(c, "streaming", replica.GetState())
		assert.True(c, replica.GetInSync(), "replica lag is %d bytes", replica.GetLagBytes())
	}, pgStreamingTimeout, pgStreamingPoll)

	targetReq := &velez_api.GetPgReplicationStatus_Request{Instance: target}

	status, err := env.PgaasClient().GetPgReplicationStatus(t.Context(), targetReq)
	require.NoError(t, err)
	require.True(t, status.GetIsReplica())
	require.True(t, status.GetInRecovery())
}

func requirePgStreamingFixture(t *testing.T, db *sql.DB) {
	t.Helper()

	const (
		subscriptionCount = `SELECT count(*) FROM subscriptions JOIN users ON users.id = subscriptions.user_id`
		workbenchStatus   = `SELECT workbenches.status FROM workbenches JOIN users ON users.id = workbenches.user_id
WHERE users.name = 'Ada'`
	)

	requirePgFixtureValue(t, db, "SELECT count(*) FROM pg_type WHERE typname = 'workbench_status'", 1)
	requirePgFixtureValue(t, db, "SELECT count(*) FROM users", 2)
	requirePgFixtureValue(t, db, subscriptionCount, 2)
	requirePgFixtureValue(t, db, workbenchStatus, "running")
	requirePgFixtureValue(t, db, "SELECT count(*) FROM replicated_rows", 3)
	requirePgFixtureValue(t, db, "SELECT last_value FROM replicated_rows_id_seq", 3)
	requirePgFixtureValue(t, db, "SELECT count(*) FROM pg_roles WHERE rolname = 'fixture_writer'", 1)
	requirePgFixtureValue(t, db, "SELECT has_table_privilege('fixture_writer', 'replicated_rows', 'INSERT')", true)
}

func requirePgStreamingInsert(t *testing.T, db *sql.DB) {
	t.Helper()

	const query = `
SELECT (SELECT count(*) FROM replicated_rows), last_value
FROM replicated_rows_id_seq`

	ctx, cancel := context.WithTimeout(t.Context(), pgStreamingTimeout)
	defer cancel()

	require.EventuallyWithT(t, func(c *assert.CollectT) {
		var count, lastValue int

		err := db.QueryRowContext(ctx, query).Scan(&count, &lastValue)
		if !assert.NoError(c, err) {
			return
		}

		assert.Equal(c, 4, count, "replicated row count")
		assert.Equal(c, 4, lastValue, "replicated sequence value")
	}, pgStreamingTimeout, pgStreamingPoll)
}

func requirePgFixtureValue[T comparable](t *testing.T, db *sql.DB, query string, want T) {
	t.Helper()

	var got T

	err := db.QueryRowContext(t.Context(), query).Scan(&got)
	require.NoError(t, err, "%s", query)
	require.Equal(t, want, got, "%s", query)
}

func createPgWithCleanup(t *testing.T, env *TestEnvironment, name string) *velez_api.PgInstance {
	t.Helper()

	dockerClient := env.DockerClient()
	removeProvisioningPgInstance(dockerClient, name)
	t.Cleanup(func() { removeProvisioningPgInstance(dockerClient, name) })

	instance := createReplicationPg(t, env, name)
	require.NotNil(t, instance, "expected %q in ListPgInstances", name)

	return instance
}

