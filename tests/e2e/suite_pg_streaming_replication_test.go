func enablePgStreaming(t *testing.T, env *TestEnvironment, name string) {
	t.Helper()

	req := &velez_api.EnablePgReplication_Request{Name: name}

	resp, err := env.PgaasClient().EnablePgReplication(t.Context(), req)
	require.NoError(t, err)

	task := env.AwaitTask(t, resp.GetEntityId(), resp.GetAction())
	require.Equal(t, velez_api.TaskStatus_DONE, task.GetStatus(), task.GetError())
}

